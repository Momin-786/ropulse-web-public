import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base = process.argv[2] || 'http://127.0.0.1:3001';
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL === 'chromium' ? {} : { channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' }) });
await fs.mkdir('tmp/qa', { recursive: true });
const results = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'load' });
  assert.equal(await page.locator('.page-transition').evaluate(node => getComputedStyle(node).animationName), 'none');
  assert.equal(await page.locator('.product-preview').evaluate(node => getComputedStyle(node).backgroundColor), 'rgba(0, 0, 0, 0)');
  await page.screenshot({ path: 'tmp/qa/hero-light-desktop.png', fullPage: false });
  await page.goto(`${base}/docs`, { waitUntil: 'load' });
  assert.equal(await page.locator('.guide-card').count(), 15);
  assert.match(await page.locator('meta[name=robots]').getAttribute('content'), /noindex/);
  await page.screenshot({ path: 'tmp/qa/illustrated-manual-index.png', fullPage: true });
  await page.goto(`${base}/docs/register-and-checkout`, { waitUntil: 'load' });
  assert.equal(await page.locator('figure.manual-screenshot').count(), 3);
  assert.match(await page.locator('meta[name=robots]').getAttribute('content'), /noindex/);
  const trigger = page.locator('.screenshot-trigger').first();
  await trigger.click();
  const dialog = page.getByRole('dialog');
  assert.equal(await dialog.isVisible(), true);
  await dialog.locator('img').evaluate(img => img.decode());
  await page.screenshot({ path: 'tmp/qa/manual-screenshot-dialog.png' });
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(), 0);
  assert.equal(await trigger.evaluate(node => node === document.activeElement), true);
  await trigger.click();
  await page.getByRole('button', { name: 'Close screenshot', exact: true }).click();
  assert.equal(await trigger.evaluate(node => node === document.activeElement), true);
  await page.screenshot({ path: 'tmp/qa/illustrated-register-desktop.png', fullPage: true });
  for (const slug of ['products-and-layouts', 'restaurant-and-kitchen', 'payments-and-receipts']) {
    await page.goto(`${base}/docs/${slug}`, { waitUntil: 'load' });
    assert.ok(await page.locator('.manual-screenshot').count());
    for (const img of await page.locator('.screenshot-trigger img').all()) await img.evaluate(image => image.decode());
  }
  await page.goto(`${base}/docs/website-account-and-billing`, { waitUntil: 'load' });
  assert.equal(await page.getByText('Planned account and billing release.', { exact: true }).count(), 1);
  results.push('All 15 manuals visible with draft labels/noindex; planned billing remains labelled; real images load in four task guides');
  results.push('Screenshot dialog: opens, image loads, Escape and close restore focus');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base, { waitUntil: 'load' });
  await page.screenshot({ path: 'tmp/qa/hero-light-mobile.png', fullPage: false });
  await page.goto(`${base}/docs/register-and-checkout`, { waitUntil: 'load' });
  await page.locator('.manual-screenshot').first().scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'tmp/qa/illustrated-register-mobile.png' });
  await page.locator('.screenshot-trigger').first().click();
  assert.equal(await page.getByRole('dialog').isVisible(), true);
  assert.ok(await page.getByRole('dialog').evaluate(node => node.scrollWidth <= node.clientWidth), 'Mobile dialog overflows');
  await page.keyboard.press('Escape');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  results.push('Mobile hero, illustrated guide and screenshot dialog fit 390px; reduced-motion disables animation');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.goto(base, { waitUntil: 'load' });
  assert.equal(await page.locator('.page-transition').evaluate(node => getComputedStyle(node).animationName), 'page-arrive');
  await page.getByRole('link', { name: 'Resources', exact: true }).click();
  await page.waitForURL('**/resources');
  await page.getByRole('heading', { level: 1 }).waitFor();
  assert.equal(await page.locator('.page-transition').evaluate(node => getComputedStyle(node).animationName), 'page-arrive');
  const lastCard = page.locator('.resource-card').last();
  await lastCard.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => { const node = document.querySelector('.resource-card:last-child'); return node && !node.classList.contains('reveal-pending') && getComputedStyle(node).opacity === '1'; });
  assert.equal(await lastCard.evaluate(node => getComputedStyle(node).opacity), '1');
  results.push('Normal motion: route-entry animation and scroll reveal work on client navigation');
  assert.deepEqual(errors, []);
  await page.close();
  const noJS = await browser.newPage({ javaScriptEnabled: false });
  await noJS.goto(`${base}/resources`, { waitUntil: 'load' });
  assert.equal(await noJS.locator('.reveal-pending').count(), 0);
  assert.equal(await noJS.getByRole('heading', { level: 1 }).isVisible(), true);
  results.push('Without JavaScript: content and resource navigation remain visible');
  await fs.writeFile('tmp/qa/motion-manuals-results.json', JSON.stringify({ checkedAt: new Date().toISOString(), results }, null, 2));
  results.forEach(result => console.log(`PASS  ${result}`));
} finally { await browser.close(); }
